"""Text-protocol agent loop for the DeepEyesV2 / Thyme baselines.

Unlike `utils/agent.py` (native OpenAI function-calling), these baselines were
trained to emit Python inside ``<code>```python ... ```</code>`` text blocks
(and, for DeepEyesV2, ``<tool_call>`` JSON for web search). An external sandbox
runs the cell and the result is fed back as the next user turn. This module
reproduces that protocol so the served checkpoint behaves as it was trained.

System / user prompts are copied verbatim from each repo:
  - Thyme:      eval/VLMEvalKit/vlmeval/vlm/thyme/utils.py
  - DeepEyesV2: evaluation/inference_demo/inference_demo.py

The returned ``(pred, meta)`` matches `utils/agent.run` so the rest of the eval
pipeline (extractor → judge, trace writing, aggregation) is unchanged.

Note on search (DeepEyesV2): this is an *offline* eval framework with no live
Google Lens / web API, so ``<tool_call>`` search requests are answered with a
graceful "search unavailable" message, nudging the model to rely on code or
answer directly. The code (python) tool is fully functional.
"""

from __future__ import annotations

import re
from typing import Any

from harness.tools.code_sandbox import CodeSandboxTool

from ..core.io import encode_image
from ..core.llm import LLMClient
from .grounding import (
    computer_use_tools_block, grounding_click_instruction,
)

# --- Thyme prompts (verbatim from the Thyme repo) --------------------------
THYME_SYSTEM_PROMPT = (
    "You are a helpful assistant.\n\n"
    "Solve the following problem step by step, and optionally write Python code "
    "for image manipulation to enhance your reasoning process. The Python code "
    "will be executed by an external sandbox, and the processed image or result "
    "(wrapped in <sandbox_output></sandbox_output>) can be returned to aid your "
    "reasoning and help you arrive at the final answer.\n\n"
    "**Reasoning & Image Manipulation (Optional but Encouraged):**\n"
    "    * You have the capability to write executable Python code to perform "
    "image manipulations (e.g., cropping to a Region of Interest (ROI), resizing, "
    "rotation, adjusting contrast) or perform calculation for better reasoning.\n"
    "    * The code will be executed in a secure sandbox, and its output will be "
    "provided back to you for further analysis.\n"
    "    * All Python code snippets **must** be wrapped as follows:\n"
    "    <code>\n    ```python\n    # your code.\n    ```\n    </code>\n"
    "    * At the end of the code, print the path of the processed image "
    "(processed_path) or the result for further processing in a sandbox environment."
)


def thyme_user_prompt(question: str, image_path: str, image_size: str) -> str:
    return (
        f"<image>\n{question}\n\n"
        f'### User Image Path:** "{image_path}"\n'
        f'### User Image Size:** "{image_size}"\n\n'
        "### **Output Format (strict adherence required):**\n\n"
        "<think>Your detailed reasoning process, including any code, should go "
        "here.</think>\n<answer>Your final answer to the user's question goes "
        "here.</answer>\n"
    )


# --- DeepEyesV2 prompts (verbatim from inference_demo.py) ------------------
DEEPEYESV2_SYSTEM_PROMPT = """You are an agent - please keep going until the user's query is completely resolved, before ending your turn and yielding back to the user. Only terminate your turn when you are sure that the problem is solved.

Solve the following problem step by step. In your reasoning process, if the answer cannot be determined, you can write Python code in a Jupyter Notebook to process the image and extract more information from it. The stdout and stderr content, along with the images generated by `plt.show()` will be returned to better assist with the user query.

You MUST use the python tool to analyze or transform images whenever it could improve your understanding. This includes but is not limited to zooming in, rotating, adjusting contrast, computing statistics, or isolating features.

For all the provided images, in order, the i-th image has already been read into the global variable "image_i" using the "PIL.Image.open()" function. When writing Python code, you can directly use these variables without needing to read them again.

## Tools

## python
Your python code should be enclosed within <code> </code> tag.

Example for calling Python code in Jupyter Notebook:
<code>
```python
# python code here
```
</code>

Note:
1. **python** can be called to analyze the image. **python** will respond with the output of the execution or time out.
2. Like jupyter notebook, you can use Python code to process the input image and use `plt.show()` to visualize processed images in your code.
3. All python code are running in the same jupyter notebook kernel, which means the functions and variables are automatically stored after code execution.
4. You program should always returns in finite time. Do not write infinite loop in your code.
5. Writing file to disk is not allowed.
"""

DEEPEYESV2_USER_PROMPT = (
    "<image>\n{question}\n\n"
    "You must put your answer inside <answer> </answer> tags, i.e., "
    "<answer> answer here </answer>. Please reason step by step. Use Python code "
    "to process the image if necessary. Format strictly as <think> </think> "
    "<code> </code> (if code is needed) or <think> </think> <answer> </answer>."
)

# --- GUI grounding (ScreenSpot-Pro) prompts -------------------------------
# Unified protocol with the base model: the standard Qwen2.5-VL `computer_use`
# tool is defined in the system prompt (see `_build_messages`), and the final
# click is committed as a `computer_use` <tool_call> with an ABSOLUTE-pixel
# coordinate. The caller (`eval.py`) feeds a PRE-RESIZED screenshot (smart_resize,
# same as the scorer) and the system prompt declares that resized resolution, so
# the click is in the resized space the scorer maps back to original pixels. Each
# model keeps its NATIVE <code> crop/zoom protocol; we only add the computer_use
# commit channel so all Qwen2.5-VL models are scored under one protocol.
_COMMIT_INSTRUCT = (
    "When you are ready, commit the click as exactly one `computer_use` tool call "
    "(and nothing after it):\n"
    '<tool_call>\n{"name": "computer_use", "arguments": {"action": "left_click", '
    '"coordinate": [x, y]}}\n</tool_call>'
)


def thyme_grounding_user_prompt(question: str, image_path: str,
                                image_size: str) -> str:
    return (
        f"<image>\n{grounding_click_instruction(question)}\n\n"
        f'### User Image Path:** "{image_path}"\n'
        f'### User Image Size:** "{image_size}"\n\n'
        "You may first reason and optionally write Python code wrapped in "
        "<code>```python ... ```</code> to crop/zoom the screenshot (its output "
        "returns in <sandbox_output>).\n"
        + _COMMIT_INSTRUCT
    )


def deepeyesv2_grounding_user_prompt(question: str) -> str:
    return (
        f"<image>\n{grounding_click_instruction(question)}\n\n"
        "You may first write Python code in <code> </code> to crop/zoom the "
        "screenshot (stdout and plt.show() images are returned).\n"
        + _COMMIT_INSTRUCT
    )

# Sandbox cannot reach a live search backend in this offline eval.
_SEARCH_UNAVAILABLE = (
    "<tool_response>\n"
    "Search is not available in this environment. Please rely on the python "
    "tool and the image content to answer, then give your final answer inside "
    "<answer> </answer> tags.\n"
    "</tool_response>"
)

_CODE_RE = re.compile(r"<code>(.*?)</code>", re.DOTALL)
_FENCE_RE = re.compile(r"```(?:python)?\s*\n?(.*?)\n?```", re.DOTALL)
_TOOLCALL_RE = re.compile(r"<tool_call>(.*?)</tool_call>", re.DOTALL)
_ANSWER_RE = re.compile(r"<answer>(.*?)</answer>", re.DOTALL)


def _image_wh(path: str) -> tuple[int, int] | None:
    """Return ``(width, height)`` of the image, or None on error. Used to declare
    the (already pre-resized) screen resolution in the computer_use tools block."""
    try:
        from PIL import Image

        with Image.open(path) as img:
            return img.width, img.height
    except Exception:  # noqa: BLE001
        return None


def _image_size(path: str) -> str:
    wh = _image_wh(path)
    return f"{wh[0]}x{wh[1]}" if wh else "Unable to determine (error reading image)"


def _extract_code(text: str) -> str | None:
    """Return the last <code> block's Python source, stripping ```python fences.

    Tolerates an unbalanced fence (the closing ``` may be missing when the
    server truncated generation on the </code> stop string)."""
    blocks = _CODE_RE.findall(text)
    if not blocks:
        return None
    inner = blocks[-1].strip()
    fenced = _FENCE_RE.findall(inner)
    if fenced:
        code = fenced[-1]
    else:
        # No complete fence: drop a leading ```/```python line and any trailing ```.
        code = re.sub(r"^```[a-zA-Z]*\s*\n?", "", inner)
        code = re.sub(r"\n?```\s*$", "", code)
    code = code.strip()
    return code or None


def _close_open_tags(text: str) -> str:
    """When the server truncates generation on a stop string, the closing tag
    is dropped. Re-append it so the transcript and parsers stay well-formed."""
    for open_t, close_t in (("<code>", "</code>"),
                            ("<tool_call>", "</tool_call>"),
                            ("<answer>", "</answer>")):
        if text.count(open_t) > text.count(close_t):
            text = text + close_t
    return text


def _build_messages(variant: str, question: str, image_paths: list[str],
                    grounding: bool = False) -> list[dict]:
    """System + user seed messages with images encoded as data URIs."""
    first = image_paths[0] if image_paths else ""
    if variant == "thyme":
        system = THYME_SYSTEM_PROMPT
        user_text = (thyme_grounding_user_prompt(question, first, _image_size(first))
                     if grounding
                     else thyme_user_prompt(question, first, _image_size(first)))
    else:
        system = DEEPEYESV2_SYSTEM_PROMPT
        user_text = (deepeyesv2_grounding_user_prompt(question) if grounding
                     else DEEPEYESV2_USER_PROMPT.format(question=question))

    # Grounding: append the standard computer_use tool definition (declaring the
    # pre-resized screen resolution) so the agent commits via the same channel as
    # the base model. The native <code> protocol stays in the system prompt above.
    if grounding:
        wh = _image_wh(first) or (0, 0)
        system = (system + "\n\n"
                  "You also have a GUI control tool for committing the final click.\n\n"
                  + computer_use_tools_block(wh[0], wh[1]))

    content: list[dict] = [
        {"type": "image_url", "image_url": {"url": encode_image(p)}}
        for p in image_paths
    ]
    content.append({"type": "text", "text": user_text})
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": content},
    ]


async def run_code_agent(question: str, image_paths: list[str], llm: LLMClient,
                         sandbox: CodeSandboxTool, variant: str,
                         max_steps: int = 20,
                         on_step=None,
                         grounding: bool = False,
                         greedy: bool = False) -> tuple[str, dict[str, Any]]:
    """Drive a code-as-tool baseline. Returns ``(pred, meta)`` matching
    `utils.agent.run`. ``pred`` is the final assistant message (the downstream
    extractor pulls the <answer> content, or the GUI scorer the pyautogui click).

    ``grounding=True`` switches to the ScreenSpot-Pro GUI-agent prompt: the
    agent may still crop/zoom with the python tool, but it commits the click as a
    ``computer_use`` ``<tool_call>`` (same protocol as the base model).

    ``greedy=True`` forces ``temperature=0`` decoding (used for grounding, to
    align with the official harness and make the click deterministic).

    ``on_step(rounds, n_tool_calls)`` is called after each LLM turn for the
    live dashboard, mirroring `utils.agent.run`."""
    # Grounding: <code> crops/zooms, a computer_use <tool_call> commits the click
    # (<answer> kept as a tolerated fallback). The deepeyesv2 search tool_call has
    # no place in a grounding task, so it is not interpreted as search below.
    if grounding:
        stop = ["</code>", "</tool_call>", "</answer>"]
    elif variant == "deepeyesv2":
        stop = ["</code>", "</tool_call>", "</answer>"]
    else:
        stop = ["</code>", "</answer>"]

    messages = _build_messages(variant, question, image_paths, grounding=grounding)
    input_messages = [dict(m) for m in messages]

    # Greedy decoding for grounding (deterministic click; aligns with the
    # official ScreenSpot-Pro harness). Overrides the endpoint's sampling temp.
    sampling: dict[str, Any] = {"temperature": 0.0, "top_p": 1.0} if greedy else {}

    turns: list[dict[str, Any]] = []
    total_p = total_c = total_t = 0
    stopped_reason = "budget"
    pred = ""

    for step in range(max_steps):
        resp = await llm.chat(messages=messages, stop=stop, **sampling)
        dump = resp.model_dump(exclude_none=True)
        usage = dump.get("usage") or {}
        total_p += usage.get("prompt_tokens", 0) or 0
        total_c += usage.get("completion_tokens", 0) or 0
        total_t += usage.get("total_tokens", 0) or 0

        choice = resp.choices[0]
        text = _close_open_tags(choice.message.content or "")

        turn: dict[str, Any] = {
            "step": step,
            "model": dump.get("model"),
            "finish_reason": choice.finish_reason,
            "message": {"role": "assistant", "content": text},
            "usage": usage,
            "tool_results": [],
        }
        turns.append(turn)
        messages.append({"role": "assistant", "content": text})

        def _notify():
            if on_step is not None:
                on_step(step + 1, sum(len(t["tool_results"]) for t in turns))

        # Final answer reached (grounding commits a pyautogui.click here too).
        if "<answer>" in text:
            pred = text  # keep full text; extractor handles <answer> parsing
            stopped_reason = "final"
            _notify()
            break

        code = _extract_code(text)
        if code is not None:
            blocks = await sandbox.execute(code=code)
            messages.append({"role": "user", "content": blocks})
            turn["tool_results"].append(
                {"name": "python", "args": {"code": code}, "result": blocks})
            _notify()
            continue

        # Grounding commit: a computer_use <tool_call> (with no code to run) ends
        # the episode. The scorer pulls the [x, y] coordinate out of `pred`.
        if grounding and _TOOLCALL_RE.search(text):
            pred = text
            stopped_reason = "final"
            _notify()
            break

        if variant == "deepeyesv2" and not grounding and _TOOLCALL_RE.search(text):
            messages.append({"role": "user", "content": _SEARCH_UNAVAILABLE})
            turn["tool_results"].append(
                {"name": "search", "args": {}, "result": _SEARCH_UNAVAILABLE})
            _notify()
            continue

        # No actionable tag and no <answer>: treat the text as the answer.
        if text.strip():
            pred = text
            stopped_reason = "final"
        else:
            stopped_reason = "empty_reply"
        _notify()
        break

    meta = {
        "input_messages": input_messages,
        "turns": turns,
        "usage_total": {
            "prompt_tokens": total_p,
            "completion_tokens": total_c,
            "total_tokens": total_t,
        },
        "n_steps": len(turns),
        "n_tool_calls": sum(len(t["tool_results"]) for t in turns),
        "stopped_reason": stopped_reason,
    }
    return pred, meta
